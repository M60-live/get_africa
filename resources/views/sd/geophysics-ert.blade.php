								</div>
								<p class="pbmit-firstletter">The uppermost tens of meters beneath Earth’s surface has been studied for several decades by water specialists, soil scientists, ecologists, geologists, geotechnical engineers, environmentalists, and agricultural engineers. That portion of Earth both affects and is impacted by human activity such as building, excavating, tunneling, and storing or accidentally releasing hazardous materials.<br>Electrical Resistivity Tomography (ERT) is a cost effective, non-distractive geophysical technique that images variations in the electrical resistivity of the subsurface.</p>
								<p>ERT technique is a 2D electrical imaging survey which is carried out using a large number of electrodes connected to a multi-core cable. In order to obtain a 2D electrical image as shown in the middle picture above, a horizontal and vertical data coverage is achieved by automatic sequential measurements of current and potential locations.<br>ERT survey has the ability to delineate geological formation, regions that are fit for erecting foundation of structures and to locate groundwater bearing formation. It is used to investigate depths of overburden and bedrock interface and has a minimal impact on the environment while providing high resolution images of the subsurface. It has been widely used to complement geotechnical investigations.<br>ERT is a cost effective, non destructive geophysical technique that images lateral variations in the electrical resistivity of the subsurface;  has rapid data collection, with typically over 600 m of continuous line data collected in a day.</p>
								
